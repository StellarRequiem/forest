#!/usr/bin/env python3
"""
🌲 Forest ARP Network Monitor
Purpose: Detect duplicate MACs, ARP spoofing, and suspicious mappings
Generated by Forest v1.9.17
"""
import subprocess
import re
from datetime import datetime
import time
import argparse

def monitor_arp(watch=False, interval=10):
    print(f"🌲 Forest ARP Monitor started at {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print("   Watching for duplicate MACs or flapping IPs\n")
    
    while True:
        try:
            arp = subprocess.check_output(["arp", "-a"], text=True, timeout=8)
            mac_to_ips = {}
            for line in arp.splitlines():
                # Fixed regex - no double escaping
                match = re.search(r'\(([\d.]+)\) at ([0-9a-f:]+)', line, re.IGNORECASE)
                if match:
                    ip = match.group(1)
                    mac = match.group(2).lower()
                    # Skip obvious multicast / broadcast
                    if mac.startswith(("ff:ff", "01:00", "33:33")) or mac in ["00:00:00:00:00:00", "1:0:5e:0:0:fb"]:
                        continue
                    mac_to_ips.setdefault(mac, []).append(ip)
            
            suspicious = False
            for mac, ips in mac_to_ips.items():
                unique_ips = list(dict.fromkeys(ips))
                if len(unique_ips) > 2:
                    print(f"⚠️ ALERT [{datetime.now().strftime('%H:%M:%S')}] MAC {mac} seen on {len(unique_ips)} IPs → {unique_ips}")
                    suspicious = True
                else:
                    print(f"✅ {mac} → {unique_ips[0]}")
            
            if not suspicious:
                print(f"✅ Network clean at {datetime.now().strftime('%H:%M:%S')}")
            
            if not watch:
                break
            print(f"   Sleeping {interval}s... (Ctrl+C to stop)\n")
            time.sleep(interval)
            
        except KeyboardInterrupt:
            print("\n🌲 Monitor stopped by user.")
            break
        except Exception as e:
            print(f"Monitor error: {e}")
            if not watch:
                break
            time.sleep(interval)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Forest ARP Monitor")
    parser.add_argument("--watch", action="store_true", help="Continuous monitoring")
    parser.add_argument("--interval", type=int, default=10, help="Seconds between checks")
    args = parser.parse_args()
    monitor_arp(watch=args.watch, interval=args.interval)
